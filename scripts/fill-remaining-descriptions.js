const run = async () => {
  const data = await fs.readJson(DATA_FILE);
  let updated = 0;
  const stillEmpty = [];
  data.sites.forEach((site) => {
    if ((site.description || '').trim()) return;
    const description = MANUAL_DESCRIPTIONS[site.id];
    if (description) {
      site.description = description;
      updated++;
    } else {
      stillEmpty.push(site.name);
    }
  });
  await fs.writeJson(DATA_FILE, data, { spaces: 2 });
  console.log(`完成：人工补全 ${updated} 个站点简介`);
  if (stillEmpty.length > 0) {
    console.log(`仍为空（页面显示域名兜底）: ${stillEmpty.join('、')}`);
  }
};

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
